INSERT INTO public.donor_responses (request_id, donor_id, status, eta_minutes, distance_km, message)
SELECT
  req.id,
  don.id,
  'accepted',
  15 + (RANDOM() * 25)::INT,
  1.5 + (RANDOM() * 4.0)::NUMERIC(4,2),
  'আমি রওনা হচ্ছি, দ্রুত পৌঁছানোর চেষ্টা করব।'
FROM (SELECT id FROM public.emergency_requests LIMIT 16) req
CROSS JOIN LATERAL (
  SELECT id FROM public.donor_profiles ORDER BY RANDOM() LIMIT 1
) don
ON CONFLICT (request_id, donor_id) DO NOTHING;

